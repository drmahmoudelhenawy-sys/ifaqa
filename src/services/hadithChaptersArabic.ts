export function getArabicChapterName(collection: HadithCollectionId, bookNumber: number, englishFallback?: string): string {
  switch (collection) {
    case 'bukhari':
      return BUKHARI_ARABIC_CHAPTERS[bookNumber] || englishFallback || `كتاب رقم ${bookNumber}`;
    case 'muslim':
      return MUSLIM_ARABIC_CHAPTERS[bookNumber] || englishFallback || `كتاب رقم ${bookNumber}`;
    case 'abudawud':
      return ABUDAWUD_ARABIC_CHAPTERS[bookNumber] || englishFallback || `كتاب رقم ${bookNumber}`;
    case 'tirmidhi':
      return TIRMIDHI_ARABIC_CHAPTERS[bookNumber] || englishFallback || `كتاب رقم ${bookNumber}`;
    case 'nasai':
      return NASAI_ARABIC_CHAPTERS[bookNumber] || englishFallback || `كتاب رقم ${bookNumber}`;
    case 'ibnmajah':
      return IBNMAJAH_ARABIC_CHAPTERS[bookNumber] || englishFallback || `كتاب رقم ${bookNumber}`;
    default:
      return englishFallback || `كتاب رقم ${bookNumber}`;
  }
}
